const std::array<Board, kCount + 1> &levels()
{
    static const std::array<Board, kCount + 1> kTable = [] {
        std::array<Board, kCount + 1> table {};
        for (int level = 0; level < kCount; ++level)
            for (int r = 0; r < kRows; ++r)
                for (int c = 0; c < kCols; ++c)
                    table[level + 1][r][c] = kRawLevels[level][r][c];
        return table;
    }();
    return kTable;
}

